<?php

namespace App\Services;

use App\Models\AgentExecution;
use App\Models\Brand;
use App\Models\BrandContentDraft;
use App\Models\User;
use Illuminate\Support\Facades\Http;

class AiGenerationService
{
    public function __construct(protected BrandContentDraftService $draftService) {}

    public function generate(Brand $brand, User $user, array $data): BrandContentDraft
    {
        $provider = strtolower($data['provider'] ?? config('services.ai.default_provider', 'internal'));
        $prompt = $data['prompt'] ?? 'Write a concise social media post for this brand.';
        $platform = $data['platform'] ?? 'linkedin';
        $contentType = $data['content_type'] ?? 'caption';

        if ($provider === 'internal') {
            $draft = $this->draftService->generateForBrand($brand, $user, [
                ...$data,
                'platform' => $platform,
                'content_type' => $contentType,
                'prompt' => $prompt,
                'status' => $data['status'] ?? 'draft',
                'ai_provider' => 'internal',
                'ai_model' => $this->providerModel('internal'),
            ]);
            $draft->update(['is_ai_generated' => false]);

            app(DashboardNotificationService::class)->notify(
                $user,
                'Content generation completed',
                $draft->title.' was created using the internal template generator.',
                $brand->id,
                '/brands/'.$brand->id,
            );

            AgentExecution::create([
                'user_id' => $user->id,
                'brand_id' => $brand->id,
                'agent_key' => 'content_writing',
                'status' => 'completed',
                'message' => 'Generated content draft using internal deterministic generator.',
                'started_at' => now(),
                'completed_at' => now(),
            ]);

            return $draft->fresh();
        }

        try {
            $generated = $this->generateContentForProvider($brand, $provider, $platform, $contentType, $prompt);
        } catch (\Throwable) {
            $generated = [
                'body' => $this->generateInternalFallback($brand, $platform, $contentType, $prompt),
                'is_ai_generated' => false,
            ];
        }
        $actualProvider = $generated['is_ai_generated'] ? $provider : 'internal';
        $body = $generated['body'];
        $draft = BrandContentDraft::query()->create([
            'user_id' => $user->id,
            'brand_id' => $brand->id,
            'title' => $data['title'] ?? $brand->name.' '.$platform.' '.$contentType,
            'platform' => $platform,
            'content_type' => $contentType,
            'status' => $data['status'] ?? 'draft',
            'prompt' => $prompt,
            'body' => $body,
            'hashtags' => $this->extractHashtags($body),
            'metadata' => [
                'provider' => $actualProvider,
                'brand_voice' => $brand->tone ?? $brand->settings?->brand_voice ?? 'confident and practical',
                'audience' => $brand->audience ?? 'target audience',
            ],
            'scheduled_for' => $data['scheduled_for'] ?? null,
            'ai_provider' => $actualProvider,
            'ai_model' => $this->providerModel($actualProvider),
            'is_ai_generated' => $generated['is_ai_generated'],
        ]);

        app(DashboardNotificationService::class)->notify(
            $user,
            'Content generation completed',
            $draft->title.($generated['is_ai_generated']
                ? ' was generated by '.$provider.'.'
                : ' was saved using an internal fallback because the provider did not return usable content.'),
            $brand->id,
            '/brands/'.$brand->id,
        );

        AgentExecution::create([
            'user_id' => $user->id,
            'brand_id' => $brand->id,
            'agent_key' => 'content_writing',
            'status' => 'completed',
            'message' => $generated['is_ai_generated']
                ? 'Generated ' . $contentType . ' draft using ' . $provider . ' (' . $this->providerModel($provider) . ').'
                : 'Generated draft using internal fallback template.',
            'started_at' => now(),
            'completed_at' => now(),
        ]);

        return $draft;
    }

    protected function generateContentForProvider(Brand $brand, string $provider, string $platform, string $contentType, string $prompt): array
    {
        $apiKey = match ($provider) {
            'openai' => config('services.ai.providers.openai.api_key', env('OPENAI_API_KEY')),
            'gemini' => config('services.ai.providers.gemini.api_key', env('GEMINI_API_KEY')),
            'openrouter' => config('services.ai.providers.openrouter.api_key', env('OPENROUTER_API_KEY')),
            'groq' => config('services.ai.providers.groq.api_key', env('GROQ_API_KEY')),
            'ollama' => config('services.ai.providers.ollama.base_url', env('OLLAMA_BASE_URL', 'http://127.0.0.1:11434')),
            default => null,
        };

        if ($provider === 'ollama' && blank($apiKey)) {
            $apiKey = config('services.ai.providers.ollama.base_url', 'http://localhost:11434');
        }

        if (blank($apiKey) && $provider !== 'ollama') {
            return [
                'body' => $this->generateInternalFallback($brand, $platform, $contentType, $prompt),
                'is_ai_generated' => false,
            ];
        }

        $response = match ($provider) {
            'openai' => Http::withHeaders([
                'Authorization' => 'Bearer '.$apiKey,
                'Content-Type' => 'application/json',
            ])->timeout(60)->post('https://api.openai.com/v1/chat/completions', [
                'model' => $this->providerModel($provider),
                'messages' => [
                    ['role' => 'user', 'content' => $this->buildPrompt($brand, $platform, $contentType, $prompt)],
                ],
                'temperature' => 0.7,
            ]),
            'gemini' => Http::withHeaders([
                'Content-Type' => 'application/json',
            ])->timeout(60)->post('https://generativelanguage.googleapis.com/v1beta/models/'.$this->providerModel($provider).':generateContent?key='.$apiKey, [
                'contents' => [[
                    'parts' => [[
                        'text' => $this->buildPrompt($brand, $platform, $contentType, $prompt),
                    ]],
                ]],
            ]),
            'openrouter' => Http::withHeaders([
                'Authorization' => 'Bearer '.$apiKey,
                'Content-Type' => 'application/json',
                'HTTP-Referer' => config('app.url', env('APP_URL', 'http://127.0.0.1:8000')),
                'X-Title' => config('app.name', env('APP_NAME', 'SocialPilot AI')),
            ])->timeout(60)->post(config('services.ai.providers.openrouter.base_url', 'https://openrouter.ai/api/v1').'/chat/completions', [
                'model' => $this->providerModel($provider),
                'messages' => [[
                    'role' => 'user',
                    'content' => $this->buildPrompt($brand, $platform, $contentType, $prompt),
                ]],
                'temperature' => 0.7,
            ]),
            'groq' => Http::withHeaders([
                'Authorization' => 'Bearer '.$apiKey,
                'Content-Type' => 'application/json',
            ])->timeout(60)->post(config('services.ai.providers.groq.base_url', 'https://api.groq.com/openai/v1').'/chat/completions', [
                'model' => $this->providerModel($provider),
                'messages' => [[
                    'role' => 'user',
                    'content' => $this->buildPrompt($brand, $platform, $contentType, $prompt),
                ]],
                'temperature' => 0.7,
            ]),
            'ollama' => Http::timeout(120)->post(rtrim($apiKey, '/').'/api/generate', [
                'model' => $this->providerModel($provider),
                'prompt' => $this->buildPrompt($brand, $platform, $contentType, $prompt),
                'stream' => false,
            ]),
            default => null,
        };

        if (! $response || ! $response->successful()) {
            return [
                'body' => $this->generateInternalFallback($brand, $platform, $contentType, $prompt),
                'is_ai_generated' => false,
            ];
        }

        $body = trim($this->extractTextFromResponse($provider, $response->json()));
        $fallback = $this->generateInternalFallbackFallbackText();
        if ($body === '' || $body === $fallback) {
            return [
                'body' => $this->generateInternalFallback($brand, $platform, $contentType, $prompt),
                'is_ai_generated' => false,
            ];
        }

        return ['body' => $body, 'is_ai_generated' => true];
    }

    protected function buildPrompt(Brand $brand, string $platform, string $contentType, string $prompt): string
    {
        return sprintf(
            "Write a polished %s %s for the brand '%s'. Audience: %s. Brand tone: %s. Prompt: %s. Keep the output concise, actionable, and ready for publishing.",
            $platform,
            $contentType,
            $brand->name,
            $brand->audience ?? 'target audience',
            $brand->tone ?? $brand->settings?->brand_voice ?? 'confident and practical',
            $prompt,
        );
    }

    protected function providerModel(string $provider): string
    {
        return match ($provider) {
            'openai' => config('services.ai.providers.openai.model', 'gpt-4o-mini'),
            'gemini' => config('services.ai.providers.gemini.model', 'gemini-1.5-flash'),
            'openrouter' => config('services.ai.providers.openrouter.model', 'meta-llama/llama-3.1-8b-instruct:free'),
            'groq' => config('services.ai.providers.groq.model', 'openai/gpt-oss-120b'),
            'ollama' => config('services.ai.providers.ollama.model', 'llama3.2:3b'),
            default => config('services.ai.providers.internal.model', 'socialpilot-lite'),
        };
    }

    protected function extractTextFromResponse(string $provider, array $payload): string
    {
        if ($provider === 'ollama') {
            return $payload['response'] ?? $this->generateInternalFallbackFallbackText();
        }

        if ($provider === 'gemini') {
            $candidates = $payload['candidates'] ?? [];
            $parts = $candidates[0]['content']['parts'] ?? [];
            $text = collect($parts)->pluck('text')->filter()->implode("\n");

            return $text ?: $this->generateInternalFallbackFallbackText();
        }

        if (isset($payload['choices'][0]['message']['content'])) {
            return $payload['choices'][0]['message']['content'];
        }

        if (isset($payload['output'])) {
            $outputText = $payload['output'];
            if (is_array($outputText)) {
                foreach ($outputText as $item) {
                    if (($item['type'] ?? null) === 'output_text' && isset($item['content'])) {
                        return is_array($item['content']) ? collect($item['content'])->pluck('text')->filter()->implode("\n") : $item['content'];
                    }
                }
            }
        }

        return $this->generateInternalFallbackFallbackText();
    }

    protected function generateInternalFallback(Brand $brand, string $platform, string $contentType, string $prompt): string
    {
        $hook = match ($platform) {
            'x' => 'A quick idea worth sharing:',
            'instagram' => 'A story your audience should save:',
            'tiktok' => 'This is the quick version worth watching:',
            'facebook' => 'A thoughtful reminder for your community:',
            default => 'Here is a practical message worth sharing:',
        };

        return $hook."\n\n"
            ."For {$brand->name}, the strongest move is to stay useful and specific.\n\n"
            ."Focus: {$prompt}\n\n"
            ."Make the message feel clear, helpful, and easy to act on. This {$contentType} should spark interest without sounding generic or forced.";
    }

    protected function generateInternalFallbackFallbackText(): string
    {
        return 'A strong message should be clear, relevant, and easy to act on. Keep the hook sharp, the value obvious, and the call to action simple.';
    }

    protected function extractHashtags(string $body): array
    {
        preg_match_all('/#([A-Za-z0-9_]+)/', $body, $matches);

        return array_values(array_unique($matches[1]));
    }
}
